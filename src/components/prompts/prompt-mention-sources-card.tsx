"use client";

import React from "react";
import { Info } from "lucide-react";
import { PromptMentionSourceItem } from "@/lib/types";
import { BrandFavicon } from "@/components/ui/favicon";

interface PromptMentionSourcesCardProps {
  mentionSources: PromptMentionSourceItem[];
  timeframeDays?: number;
}

function getSovPillClass(sovPct: number) {
  if (sovPct >= 30) {
    return "bg-emerald-500/15 text-emerald-700 font-bold border-emerald-500/25";
  }
  if (sovPct >= 18) {
    return "bg-emerald-500/10 text-emerald-600 font-semibold border-emerald-500/15";
  }
  if (sovPct >= 10) {
    return "bg-amber-500/15 text-amber-700 font-medium border-amber-500/20";
  }
  return "bg-slate-100 text-slate-600 font-medium border-slate-200";
}

export function PromptMentionSourcesCard({
  mentionSources,
  timeframeDays = 30,
}: PromptMentionSourcesCardProps) {
  const maxMentions =
    mentionSources.length > 0
      ? Math.max(...mentionSources.map((m) => m.mentions), 1)
      : 1;

  return (
    <div className="bg-white rounded-2xl border border-slate-200/80 shadow-xs overflow-hidden flex flex-col h-full">
      {/* Header */}
      <div className="p-5 border-b border-slate-100 flex items-center justify-between">
        <div className="flex items-center gap-2">
          <h3 className="text-base font-bold text-slate-900">Mention Sources</h3>
          <div className="group relative flex items-center">
            <Info className="w-3.5 h-3.5 text-slate-400 cursor-help" />
            <div className="absolute left-0 bottom-full mb-2 hidden group-hover:block z-20 w-64 p-2.5 text-[11px] leading-relaxed text-slate-700 bg-white/95 backdrop-blur-sm rounded-xl border border-slate-200/90 shadow-lg shadow-slate-900/5 pointer-events-none animate-in fade-in">
              Breakdown of total brand mentions and share of voice (SOV) generated by this prompt across model outputs.
            </div>
          </div>
        </div>
        <span className="text-xs text-slate-500 font-medium">
          Brands mentioned for this prompt
        </span>
      </div>

      {/* Table */}
      <div className="overflow-x-auto flex-1">
        <table className="w-full text-left border-collapse border-y border-slate-200">
          <thead>
            <tr className="border-b border-slate-200 divide-x divide-slate-200 text-[11px] font-semibold text-slate-500 uppercase tracking-wider bg-slate-50/75">
              <th className="py-3 px-4 w-10 text-center">#</th>
              <th className="py-3 px-4">Brand</th>
              <th className="py-3 px-4">Mentions</th>
              <th className="py-3 px-4 text-center">SOV</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-200 text-xs font-medium text-slate-700">
            {mentionSources.length === 0 ? (
              <tr>
                <td colSpan={4} className="py-8 text-center text-slate-400">
                  No brand mentions recorded for this prompt.
                </td>
              </tr>
            ) : (
              mentionSources.map((item) => {
                const barWidth = Math.max(
                  10,
                  Math.round((item.mentions / maxMentions) * 100)
                );
                return (
                  <tr
                    key={`${item.rank}-${item.name}`}
                    className="hover:bg-slate-50/70 divide-x divide-slate-200 transition-colors"
                  >
                    {/* Rank */}
                    <td className="py-3.5 px-4 text-center text-slate-400 font-bold">
                      {item.rank}
                    </td>

                    {/* Brand */}
                    <td className="py-3.5 px-4">
                      <div className="flex items-center gap-2.5">
                        <BrandFavicon
                          brandName={item.name}
                          domain={item.domain}
                          size={22}
                          className="rounded-md border border-slate-200/60 shadow-2xs"
                        />
                        <span className="font-semibold text-slate-900">
                          {item.name}
                        </span>
                        {!item.isCompetitor && (
                          <span className="inline-flex items-center px-1.5 py-0.5 rounded-full text-[10px] font-bold bg-slate-100 text-slate-700 border border-slate-200">
                            You
                          </span>
                        )}
                      </div>
                    </td>

                    {/* Mentions Count + Visual Bar */}
                    <td className="py-3.5 px-4">
                      <div className="flex items-center gap-3 max-w-[160px]">
                        <span className="font-semibold text-slate-800 shrink-0 min-w-[20px]">
                          {item.mentions}
                        </span>
                        <div className="flex-1 bg-slate-100 h-1.5 rounded-full overflow-hidden">
                          <div
                            className={`h-full rounded-full ${
                              !item.isCompetitor
                                ? "bg-indigo-600"
                                : "bg-slate-400"
                            }`}
                            style={{ width: `${barWidth}%` }}
                          />
                        </div>
                      </div>
                    </td>

                    {/* SOV Pill */}
                    <td className="py-3.5 px-4 text-center">
                      <span
                        className={`inline-flex items-center justify-center min-w-[50px] px-2.5 py-0.5 rounded-full text-xs border ${getSovPillClass(
                          item.sovPct
                        )}`}
                      >
                        {item.sov}
                      </span>
                    </td>
                  </tr>
                );
              })
            )}
          </tbody>
        </table>
      </div>

      {/* Footer */}
      <div className="p-3 bg-slate-50/50 border-t border-slate-100 text-[11px] text-slate-500 flex justify-between items-center px-5">
        <span>Last {timeframeDays} days · All models</span>
        <span className="font-semibold text-slate-700">
          {mentionSources.length} brands
        </span>
      </div>
    </div>
  );
}
